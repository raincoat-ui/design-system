// npm

/** packages/web-themes/<id>/package.json */
export function webThemePackage(theme, { version, inRepo = true }) {
  const manifest = {
    name: npmName(theme, { inRepo }),
    version,
    description: `The Raincoat ${theme.id} theme: every token as CSS custom properties, for light, dark, and high-contrast modes.`,
    license: inRepo ? "Apache-2.0" : "UNLICENSED",
  };
  if (inRepo) {
    Object.assign(manifest, {
      homepage: "https://raincoat-ui.github.io/design-system/",
      bugs: "https://github.com/raincoat-ui/design-system/issues",
      repository: {
        type: "git",
        url: "git+https://github.com/raincoat-ui/design-system.git",
        directory: `packages/web-themes/${theme.id}`,
      },
      keywords: ["design-system", "design-tokens", "css", "theme", "dark-mode", "high-contrast"],
      publishConfig: { access: "public" },
    });
  } else if (!theme.meta.packages?.npm) {
    manifest.private = true;
  }
  Object.assign(manifest, {
    exports: { "./theme.css": "./theme.css" },
    files: inRepo ? ["theme.css", "NOTICE"] : ["theme.css"],
    sideEffects: ["*.css"],
  });
  return json(manifest);
}

/** packages/web-themes/<id>/README.md */
export function webThemeReadme(theme) {
  const name = npmName(theme);
  return `<!-- GENERATED by raincoat-tokens from the theme's theme.json. Do not edit. -->

# ${name}

The Raincoat ${theme.id} theme: every design token as a CSS custom property, for four color
modes and two densities. ${theme.meta.description}

\`\`\`css
@import "${name}/theme.css";
\`\`\`

\`\`\`css
.card {
  background: var(--rc-color-bg-surface);
  color: var(--rc-color-fg-default);
  border-radius: var(--rc-radius-md);
  padding: var(--rc-space-4);
}
\`\`\`

Load one theme per page. Every theme defines the same properties, so an app changes its theme
by changing this one import.

## Color mode and density

Without any attribute, the theme follows the system: light or dark, and the "more contrast"
setting. To choose yourself, set \`data-theme\` on any element to \`light\`, \`dark\`, \`light-hc\`, or
\`dark-hc\`. Set \`data-density="compact"\` for smaller controls. Both can be nested.

\`\`\`html
<html data-theme="dark" data-density="compact">
\`\`\`

## Names

Every property starts with \`--rc-\`, followed by the token's path: the token
\`color.bg.surface\` is \`--rc-color-bg-surface\`. Use the semantic tokens (\`--rc-color-*\` by role,
\`--rc-space-*\`, \`--rc-radius-*\`, \`--rc-type-*\`) and the component tokens. The color ramps
(\`--rc-color-neutral-500\`) are the theme's raw material and may change between themes.

The [token reference](https://raincoat-ui.github.io/design-system/) lists every token with its
value in each mode.

The file is generated from the token source in
[raincoat-ui/design-system](https://github.com/raincoat-ui/design-system). Components for React
are in \`@raincoat-ui/react\`.

## License

Apache-2.0.
`;
}

