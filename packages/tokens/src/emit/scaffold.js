/** packages/ios/Package.swift: the components, the token types, and one product per theme. */
export function packageSwift(themeIds) {
  const modules = themeIds.map((id) => swiftTheme(id).module);
  const products = modules.map((module) => `.library(name: "${module}", targets: ["${module}"]),`);
  const targets = modules.map(
    (module) => `.target(name: "${module}", dependencies: ["RaincoatTokens"]),`,
  );
  const tests = modules.map(
    (module) => `.testTarget(name: "${module}Tests", dependencies: ["${module}"]),`,
  );
  const list = (items, depth) => items.map((item) => `${"    ".repeat(depth)}${item}`).join("\n");
  const quoted = ["Raincoat", ...modules].map((name) => `"${name}"`).join(", ");
  return `// swift-tools-version: 6.2
${HEADER}
import PackageDescription

// RaincoatTokens and the theme modules use Foundation only, so they also build and test on
// Linux. Raincoat is the SwiftUI layer; its sources compile to nothing where SwiftUI is
// unavailable. Each theme is a product of its own, so an app links only the theme it uses.
let package = Package(
    name: "Raincoat",
    // The components speak a few words to assistive technology. They are translated in
    // Sources/Raincoat/Resources, and English is used for any other language.
    defaultLocalization: "en",
    platforms: [.iOS(.v17), .macOS(.v14)],
    products: [
        .library(name: "Raincoat", targets: ["Raincoat"]),
        .library(name: "RaincoatTokens", targets: ["RaincoatTokens"]),
${list(products, 2)}
    ],
    targets: [
        .target(name: "RaincoatTokens"),
${list(targets, 2)}
        // The base theme is what components draw with until an app applies its own.
        .target(
            name: "Raincoat",
            dependencies: ["RaincoatTokens", "${swiftTheme("base").module}"],
            resources: [.process("Resources")]
        ),
        .testTarget(name: "RaincoatTokensTests", dependencies: ["RaincoatTokens"]),
${list(tests, 2)}
        // The component tests draw every component in every theme.
        .testTarget(name: "RaincoatTests", dependencies: [${quoted}]),
    ]
)
`;
}

