// The package files around each theme's generated values: its npm package, its place in the
// Swift package, and its Gradle module. They are generated too, so that adding a theme is
// adding a directory under themes/ and running the build, and nothing else (ADR 0018).
import { HEADER, pascal } from "./shared.js";
import { swiftTheme } from "./swift.js";

const KOTLIN_HEADER = HEADER;
const json = (value) => `${JSON.stringify(value, null, 2)}\n`;

/**
 * The npm name of a theme's stylesheet. In this repository, @raincoat-ui/theme-<id>. A theme
 * pack names its own in theme.json, or gets an unscoped name it will not publish by accident.
 */
export const npmName = (theme, { inRepo = true } = {}) =>
  theme.meta?.packages?.npm ??
  (inRepo ? `@raincoat-ui/theme-${theme.id}` : `raincoat-theme-${theme.id}`);

