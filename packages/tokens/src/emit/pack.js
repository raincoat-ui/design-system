// Builds the themes of a theme pack: a directory outside the Raincoat repository that holds
// themes/<id>/ directories, such as a private repository for brands that must not be public
// (ADR 0010). Each theme is built on the base token source this package was released with, into
// one package per platform, depending on the published Raincoat packages of the same version:
//
//   <out>/npm/<id>/            the theme's stylesheet, as an npm package
//   <out>/swift/               a Swift package with one product per theme, RaincoatTheme<Id>
//   <out>/android/             a Gradle build with one module per theme, theme-<id>
//
// The Swift and Gradle builds run their themes' contract tests, as this repository's do.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { raincoatVersion } from "../project.js";
import { buildThemeCss } from "./css.js";
import { expectedKotlin, themeKotlin, themePackage, themeTestKotlin } from "./kotlin.js";
import { npmName, webThemePackage } from "./scaffold.js";
import { HEADER, pascal } from "./shared.js";
import { expectedSwift, swiftTheme, themeSwift, themeTestsSwift } from "./swift.js";

export const SWIFT_MIRROR = "https://github.com/raincoat-ui/design-system-swift";
export const MAVEN_REPOSITORY = "https://raincoat-ui.github.io/design-system/maven";
const DEFAULT_MAVEN_GROUP = "local.raincoat";

/** The Kotlin version the Raincoat modules are built with, so a pack's modules match them. */
function kotlinVersion(baseRoot) {
  const catalog = join(baseRoot, "gradle/libs.versions.toml");
  const match = existsSync(catalog) && /^kotlin = "([^"]+)"$/m.exec(readFileSync(catalog, "utf8"));
  if (!match) throw new Error(`no Kotlin version in ${catalog}`);
  return match[1];
}

function readme(theme, version) {
  const name = npmName(theme, { inRepo: false });
  return `<!-- GENERATED by raincoat-tokens ${version} from the theme's theme.json. Do not edit. -->

# ${name}

The ${theme.meta.name} theme for Raincoat ${version}. ${theme.meta.description}

\`\`\`css
@import "${name}/theme.css";
@import "@raincoat-ui/react/ui.css";
\`\`\`

Every Raincoat token is a CSS custom property, for four color modes and two densities. Set
\`data-theme\` to \`light\`, \`dark\`, \`light-hc\`, or \`dark-hc\` to choose a mode, or leave it unset to
follow the system.
`;
}

function packageSwift(themes, version) {
  const modules = themes.map((theme) => swiftTheme(theme.id).module);
  const tokens = '.product(name: "RaincoatTokens", package: "design-system-swift")';
  const lines = (items) => items.map((item) => `        ${item}`).join("\n");
  return `// swift-tools-version: 6.2
// GENERATED by raincoat-tokens ${version}. Do not edit: change themes/ and rebuild.
import Foundation
import PackageDescription

// The themes of this theme pack, built on Raincoat ${version}. Each theme is a product of its
// own; an app adds this package beside Raincoat's and links the theme it uses. Set
// RAINCOAT_SWIFT_PATH to build against a local copy of the Raincoat Swift package instead; its
// directory must be named design-system-swift.
let raincoat: Package.Dependency =
    if let path = ProcessInfo.processInfo.environment["RAINCOAT_SWIFT_PATH"] {
        .package(path: path)
    } else {
        .package(url: "${SWIFT_MIRROR}", exact: "${version}")
    }

let package = Package(
    name: "RaincoatThemes",
    platforms: [.iOS(.v17), .macOS(.v14)],
    products: [
${lines(modules.map((module) => `.library(name: "${module}", targets: ["${module}"]),`))}
    ],
    dependencies: [raincoat],
    targets: [
${lines(modules.map((module) => `.target(name: "${module}", dependencies: [${tokens}]),`))}
${lines(
  modules.map(
    (module) => `.testTarget(name: "${module}Tests", dependencies: ["${module}", ${tokens}]),`,
  ),
)}
    ]
)
`;
}

function settingsGradle(themes, version) {
  const includes = themes.map((theme) => `include(":theme-${theme.id}")`);
  return `${HEADER}
// The themes of this theme pack, built on Raincoat ${version}: one module per theme. The token
// types come from Raincoat's Maven repository; -PraincoatRepository=<url or directory> uses
// another copy of it.
pluginManagement {
    repositories {
        gradlePluginPortal()
        mavenCentral()
    }
}

dependencyResolutionManagement {
    repositoriesMode.set(RepositoriesMode.FAIL_ON_PROJECT_REPOS)
    repositories {
        maven {
            name = "raincoat"
            url = uri(providers.gradleProperty("raincoatRepository").orElse("${MAVEN_REPOSITORY}").get())
            content { includeGroup("io.github.raincoat-ui") }
        }
        mavenCentral()
    }
}

rootProject.name = "raincoat-themes"

${includes.join("\n")}
`;
}

function themeGradle(theme, { version, baseRoot }) {
  const group = theme.meta.packages?.maven ?? DEFAULT_MAVEN_GROUP;
  return `${HEADER}
import org.jetbrains.kotlin.gradle.dsl.JvmTarget

plugins {
    kotlin("jvm") version "${kotlinVersion(baseRoot)}"
    \`maven-publish\`
}

group = "${group}"
version = "${version}"
description = "The ${theme.meta.name} theme for Raincoat: every token, for four color modes and two densities."

kotlin {
    explicitApi()
    compilerOptions {
        jvmTarget.set(JvmTarget.JVM_17)
        allWarningsAsErrors.set(true)
    }
}

java {
    sourceCompatibility = JavaVersion.VERSION_17
    targetCompatibility = JavaVersion.VERSION_17
    withSourcesJar()
}

publishing {
    publications {
        register<MavenPublication>("maven") {
            from(components["java"])
        }
    }
}

dependencies {
    api("io.github.raincoat-ui:tokens:${version}")
    testImplementation(kotlin("test"))
}

tasks.test {
    useJUnitPlatform()
}
`;
}

/** Every file of a theme pack's output, relative to `out`. */
export function packOutputs(project, { version = raincoatVersion() } = {}) {
  const themes = project.themes.filter((theme) => !theme.base);
  const files = [];
  for (const theme of themes) {
    const { id } = theme;
    const name = pascal(id);
    const { module } = swiftTheme(id);
    const kotlinDir = themePackage(id).split(".").join("/");
    files.push(
      { file: `npm/${id}/theme.css`, content: buildThemeCss(theme.files) },
      {
        file: `npm/${id}/package.json`,
        content: webThemePackage(theme, { version, inRepo: false }),
      },
      { file: `npm/${id}/README.md`, content: readme(theme, version) },
      { file: `swift/Sources/${module}/${name}Theme.swift`, content: themeSwift(theme.files, id) },
      {
        file: `swift/Tests/${module}Tests/Expected${name}Tokens.swift`,
        content: expectedSwift(theme.files, id),
      },
      { file: `swift/Tests/${module}Tests/${name}ThemeTests.swift`, content: themeTestsSwift(id) },
      {
        file: `android/theme-${id}/build.gradle.kts`,
        content: themeGradle(theme, { version, baseRoot: project.baseRoot }),
      },
      {
        file: `android/theme-${id}/src/main/kotlin/${kotlinDir}/${name}Theme.kt`,
        content: themeKotlin(theme.files, id),
      },
      {
        file: `android/theme-${id}/src/test/kotlin/${kotlinDir}/Expected${name}Tokens.kt`,
        content: expectedKotlin(theme.files, id),
      },
      {
        file: `android/theme-${id}/src/test/kotlin/${kotlinDir}/${name}ThemeTest.kt`,
        content: themeTestKotlin(id),
      },
    );
  }
  if (themes.length > 0) {
    files.push(
      { file: "swift/Package.swift", content: packageSwift(themes, version) },
      { file: "android/settings.gradle.kts", content: settingsGradle(themes, version) },
    );
  }
  return files;
}

/**
 * Writes a theme pack's output into `out`, or with `check`, reports what is out of date.
 * @returns {{file: string, status: "written" | "unchanged" | "stale"}[]}
 */
export function buildPack(project, { out, check = false }) {
  return packOutputs(project).map(({ file, content }) => {
    const path = join(out, file);
    const shown = relative(project.root, path);
    const current = existsSync(path) ? readFileSync(path, "utf8") : null;
    if (current === content) return { file: shown, status: "unchanged" };
    if (check) return { file: shown, status: "stale" };
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
    return { file: shown, status: "written" };
  });
}
